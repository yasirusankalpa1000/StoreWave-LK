export const CURRENCY_RATES = {
  LKR: 1,
  USD: 310,
  EUR: 335,
  GBP: 395
};

export const CURRENCY_SYMBOLS: Record<string, string> = {
  LKR: 'Rs. ',
  USD: '$',
  EUR: '€',
  GBP: '£'
};

export function getT(language: SupportedLanguage): Record<string, string> {
  const current = TRANSLATIONS[language] || {};
  return {
    ...TRANSLATIONS.en,
    ...current
  };
}

export function formatPrice(amountInLKR: number, currency: string = 'LKR'): string {
  const rate = CURRENCY_RATES[currency as keyof typeof CURRENCY_RATES] || 1;
  const symbol = CURRENCY_SYMBOLS[currency] || 'Rs. ';
  
  if (currency === 'LKR') {
    return `${symbol}${Math.round(amountInLKR).toLocaleString()}`;
  }
  const converted = (amountInLKR / rate).toFixed(2);
  return `${symbol}${converted}`;
}
